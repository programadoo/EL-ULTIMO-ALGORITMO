# Test ARG and QR Code Generation with Headless Chrome CDP
$chrome = "C:\Program Files\Google\Chrome\Application\chrome.exe"
$port = 9333
$userDataDir = Join-Path $env:TEMP "chrome_arg_test_profile_$([Guid]::NewGuid())"
$argUrl = "file:///" + (Resolve-Path "EL-ULTIMO-ALGORITMO\arg\index.html").Path.Replace("\", "/")

Write-Host "Launching Headless Chrome on port $port..."
$proc = Start-Process -FilePath $chrome -ArgumentList @(
    "--headless",
    "--no-sandbox",
    "--remote-debugging-port=$port",
    "--remote-allow-origins=*",
    "--user-data-dir=$userDataDir",
    "--no-first-run",
    "--no-default-browser-check",
    "--disable-gpu",
    "$argUrl"
) -PassThru

Start-Sleep -Seconds 2

try {
    # 1. Connect to CDP
    $versionJson = Invoke-RestMethod -Uri "http://127.0.0.1:$port/json"
    $wsUrl = $versionJson[0].webSocketDebuggerUrl
    Write-Host "CDP Target connected: $wsUrl"

    # Function to evaluate JS over CDP WebSocket
    $client = New-Object System.Net.WebSockets.ClientWebSocket
    $cts = New-Object System.Threading.CancellationTokenSource(10000)
    $client.ConnectAsync([System.Uri]$wsUrl, $cts.Token).Wait()

    function Invoke-CDPEval($expression) {
        $id = [int](Get-Random -Minimum 1000 -Maximum 9999)
        $msg = @{
            id = $id
            method = "Runtime.evaluate"
            params = @{
                expression = $expression
                returnByValue = $true
                awaitPromise = $true
            }
        } | ConvertTo-Json -Compress

        $bytes = [System.Text.Encoding]::UTF8.GetBytes($msg)
        $segment = [System.ArraySegment[byte]]::new($bytes)
        $ctsSend = New-Object System.Threading.CancellationTokenSource(5000)
        $client.SendAsync($segment, [System.Net.WebSockets.WebSocketMessageType]::Text, $true, $ctsSend.Token).Wait()

        $buffer = [byte[]]::new(65536)
        $recvSegment = [System.ArraySegment[byte]]::new($buffer)
        $ctsRecv = New-Object System.Threading.CancellationTokenSource(5000)
        $recvResult = $client.ReceiveAsync($recvSegment, $ctsRecv.Token)
        $recvResult.Wait()

        $respJson = [System.Text.Encoding]::UTF8.GetString($buffer, 0, $recvResult.Result.Count)
        $res = $respJson | ConvertFrom-Json
        return $res.result.result.value
    }

    # Test 1: Check Page Title and Lock Screen
    $title = Invoke-CDPEval "document.title"
    Write-Host "[TEST 1] Title: $title"
    if ($title -like "*CORTEX*") { Write-Host "PASS: Title contains CORTEX" } else { Write-Error "FAIL: Title mismatch" }

    $lockVisible = Invoke-CDPEval "getComputedStyle(document.getElementById('lock-screen')).display !== 'none'"
    Write-Host "[TEST 2] Lock screen visible: $lockVisible"
    if ($lockVisible -eq $true) { Write-Host "PASS: Lock screen is active" } else { Write-Error "FAIL: Lock screen should be visible" }

    # Test 3: Enter invalid token
    Invoke-CDPEval "document.getElementById('cipher-token-input').value = 'WRONG_TOKEN'; handleDecrypt();"
    $errText = Invoke-CDPEval "document.getElementById('decrypt-error').textContent"
    Write-Host "[TEST 3] Denied message: $errText"
    if ($errText -like "*DENEGADO*") { Write-Host "PASS: Invalid token rejected" } else { Write-Error "FAIL: Should reject wrong token" }

    # Test 4: Enter valid token VERA_DESPIERTA_2044
    Invoke-CDPEval "document.getElementById('cipher-token-input').value = 'VERA_DESPIERTA_2044'; handleDecrypt();"
    Start-Sleep -Milliseconds 500

    $dossierVisible = Invoke-CDPEval "getComputedStyle(document.getElementById('dossier-screen')).display !== 'none'"
    Write-Host "[TEST 4] Dossier screen visible: $dossierVisible"
    if ($dossierVisible -eq $true) { Write-Host "PASS: Dossier successfully unlocked" } else { Write-Error "FAIL: Dossier should be visible" }

    # Test 5: Verify QR Code Generated by JavaScript
    $hasCanvas = Invoke-CDPEval "!!document.querySelector('#qrcode-container canvas')"
    $canvasWidth = Invoke-CDPEval "document.querySelector('#qrcode-container canvas')?.width"
    $canvasHeight = Invoke-CDPEval "document.querySelector('#qrcode-container canvas')?.height"
    Write-Host "[TEST 5] QR Code canvas present: $hasCanvas, width: $canvasWidth, height: $canvasHeight"
    if ($hasCanvas -eq $true -and $canvasWidth -gt 0) {
        Write-Host "PASS: JavaScript QR Code dynamically rendered with dimensions ${canvasWidth}x${canvasHeight}"
    } else {
        Write-Error "FAIL: QR Code canvas not found or invalid dimensions"
    }

    # Test 6: Check Redeem Code Display
    $redeemCode = Invoke-CDPEval "document.getElementById('active-redeem-code')?.textContent"
    Write-Host "[TEST 6] Active redeem code: $redeemCode"
    if ($redeemCode -eq "NEXUS_ARG_CORTEX_REDEEM_77") {
        Write-Host "PASS: Redeem code is NEXUS_ARG_CORTEX_REDEEM_77"
    } else {
        Write-Error "FAIL: Redeem code mismatch"
    }

    # Test 7: Deep Link with ?token=VERA_DESPIERTA_2044
    $deepUrl = $argUrl + "?token=VERA_DESPIERTA_2044"
    Write-Host "Testing deep link: $deepUrl"
    Invoke-CDPEval "window.location.href = '$deepUrl'"
    Start-Sleep -Seconds 1

    $deepDossier = Invoke-CDPEval "getComputedStyle(document.getElementById('dossier-screen')).display !== 'none'"
    $deepCanvas = Invoke-CDPEval "!!document.querySelector('#qrcode-container canvas')"
    Write-Host "[TEST 7] Deep link unlocked: $deepDossier, canvas: $deepCanvas"
    if ($deepDossier -eq $true -and $deepCanvas -eq $true) {
        Write-Host "PASS: Deep link auto-unlocked dossier with QR Code"
    } else {
        Write-Error "FAIL: Deep link failed"
    }

    $client.CloseAsync([System.Net.WebSockets.WebSocketCloseStatus]::NormalClosure, "Done", [System.Threading.CancellationToken]::None).Wait()
} finally {
    Stop-Process -Id $proc.Id -Force -ErrorAction SilentlyContinue
    Remove-Item -Path $userDataDir -Recurse -Force -ErrorAction SilentlyContinue
    Write-Host "Cleaned up test processes and temp profile."
}
